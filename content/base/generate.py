import os

# Список всех ваших 39 тегов
tags = [
    "для-старта", "компания-6-плюс", "посмеяться", "быстрые-партии", "подумать", "популярное",
    "соло", "дуэльная", "на-3-5", "кооператив", "полукооператив", "командная", "семейная",
    "евро", "америтреш", "карточная", "колодостроение", "контроль-территорий",
    "выкладывание-тайлов", "асимметричная", "на-взятки", "гонки", "квест-и-кампания",
    "переговоры-и-интриги", "блеф-и-мафия", "ассоциации", "логика-и-головоломки",
    "словесная", "творческая", "азартная", "на-скорость-и-ловкость",
    "фэнтези", "фантастика", "хоррор-и-мистика", "детектив", "история-и-цивилизации",
    "природа-и-животные", "выживание", "по-лицензии"
]

# Папка, куда сохранятся файлы (создастся рядом со скриптом)
output_folder = "content/base"
os.makedirs(output_folder, exist_ok=True)

# Шаблон содержимого файла
template = """filters:
  and:
    - type.contains("game")
views:
  - type: cards
    name: представление 2
    filters:
      and:
        - file.tags.contains("{tag}")
    order:
      - file.name
      - tags
      - description
    image: note.image_url
    imageAspectRatio: 1
    cardSize: 250
"""

# Генерация файлов
for tag in tags:
    filename = os.path.join(output_folder, f"{tag}.base")
    with open(filename, "w", encoding="utf-8") as file:
        file.write(template.format(tag=tag))

print(f"Готово! Создано файлов: {len(tags)} в папке '{output_folder}'.")
